import Image from "next/image";
import Link from "next/link";
import type { ReactNode } from "react";
import { photoSrc, type MoodBoard } from "@/lib/mood-boards";

export type Theme = {
  bg: string;
  text: string;
  muted: string;
  mark: string; // color of the ✦ marker on generated tiles
  radius: string; // tile corner radius, e.g. "16px"
  tileBorder?: string; // e.g. "1px solid #1C1D1F"
  displayClass: string; // font class for the board title
  bodyClass: string;
  titleClass?: string; // extra styling for the title
};

/** A tile the agent generated (not one of the owner's photos). */
export function Generated({
  children,
  theme,
  style,
  className = "",
}: {
  children: ReactNode;
  theme: Theme;
  style?: React.CSSProperties;
  className?: string;
}) {
  return (
    <div
      className={`relative overflow-hidden ${className}`}
      style={{ borderRadius: theme.radius, border: theme.tileBorder, ...style }}
    >
      {children}
      <span
        aria-label="Generated by the agent"
        title="Generated by the agent"
        className="absolute right-2 top-2 text-sm leading-none"
        style={{ color: theme.mark }}
      >
        ✦
      </span>
    </div>
  );
}

export function Board({
  board,
  theme,
  generated,
}: {
  board: MoodBoard;
  theme: Theme;
  /** Generated tiles, keyed by the position (0-based) they should appear at. */
  generated: Record<number, ReactNode>;
}) {
  const photos = board.photos.map((photo, i) => (
    <Image
      key={photo.file}
      src={photoSrc(board, photo)}
      alt={photo.alt}
      width={photo.w}
      height={photo.h}
      sizes="(min-width: 1280px) 20vw, (min-width: 1024px) 25vw, (min-width: 640px) 33vw, 50vw"
      priority={i < 4}
      className="block h-auto w-full"
      style={{ borderRadius: theme.radius, border: theme.tileBorder }}
    />
  ));

  const tiles: ReactNode[] = [];
  const total = photos.length + Object.keys(generated).length;
  for (let pos = 0, p = 0; pos < total; pos++) {
    tiles.push(pos in generated ? generated[pos] : photos[p++]);
  }

  return (
    <main
      className={`min-h-screen ${theme.bodyClass}`}
      style={{ background: theme.bg, color: theme.text }}
    >
      <div className="mx-auto max-w-[1600px] px-4 py-8 sm:px-8 sm:py-12">
        <Link
          href="/"
          className="text-sm underline-offset-4 hover:underline focus-visible:underline"
          style={{ color: theme.muted }}
        >
          ← Hub
        </Link>

        <header className="mt-6 mb-8 flex flex-col gap-4 sm:mb-10 lg:flex-row lg:items-end lg:justify-between">
          <div>
            <p className="text-xs uppercase tracking-[0.2em]" style={{ color: theme.muted }}>
              Mood board
            </p>
            <h1 className={`mt-2 ${theme.displayClass} ${theme.titleClass ?? ""}`}>
              {board.name}
            </h1>
            <p className="mt-3 text-base sm:text-lg">{board.keywords.join(" · ")}</p>
          </div>
          <div className="max-w-md lg:text-right">
            <p style={{ color: theme.muted }}>{board.summary}</p>
            <p className="mt-2 text-sm" style={{ color: theme.muted }}>
              <span style={{ color: theme.mark }}>✦</span> generated by the agent
            </p>
          </div>
        </header>

        <div className="columns-2 gap-3 sm:columns-3 sm:gap-4 lg:columns-4 xl:columns-5">
          {tiles.map((tile, i) => (
            <div key={i} className="mb-3 break-inside-avoid sm:mb-4">
              {tile}
            </div>
          ))}
        </div>

        <footer className="mt-8 text-center text-sm" style={{ color: theme.muted }}>
          {total} artifacts: {photos.length} photographs, plus color, type, texture, and
          interface pieces
        </footer>
      </div>
    </main>
  );
}
